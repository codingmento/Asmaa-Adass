window.translations = translations;

const STORAGE_KEY = "asmaa-portfolio-lang";

function applyTranslations(lang) {
  const dict = translations[lang] || translations.en;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  // Special-case the "Show More / Show Fewer" button, which toggles state
  const seeMoreBtn = document.getElementById("seeMoreBtn");
  if (seeMoreBtn) {
    const isExpanded = seeMoreBtn.dataset.expanded === "true";
    seeMoreBtn.textContent = isExpanded ? dict["work.seeFewer"] : dict["work.seeMore"];
  }

  document.title = dict["meta.title"];
  const metaDesc = document.querySelector('meta[name="description"]');
  if (metaDesc) metaDesc.setAttribute("content", dict["meta.description"]);

  document.documentElement.setAttribute("lang", lang);
  document.documentElement.setAttribute("dir", lang === "ar" ? "rtl" : "ltr");

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    const isActive = btn.dataset.lang === lang;
    btn.classList.toggle("active", isActive);
    btn.setAttribute("aria-pressed", String(isActive));
  });

  localStorage.setItem(STORAGE_KEY, lang);
}

function initLanguage() {
  const saved = localStorage.getItem(STORAGE_KEY);
  const lang = saved === "ar" || saved === "en" ? saved : "en";
  applyTranslations(lang);

  document.querySelectorAll(".lang-btn").forEach((btn) => {
    btn.addEventListener("click", () => applyTranslations(btn.dataset.lang));
  });
}

document.addEventListener("DOMContentLoaded", initLanguage);
